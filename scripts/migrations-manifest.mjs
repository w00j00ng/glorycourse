import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { DatabaseSync } from 'node:sqlite';

const directory = resolve(import.meta.dirname, '../schema/migrations');
const unsafeSql = /\b(?:BEGIN|COMMIT|ROLLBACK|SAVEPOINT|RELEASE|VACUUM|ATTACH|DETACH)\b|\bPRAGMA\s+(?:journal_mode|foreign_keys|synchronous|writable_schema)\b|\b(?:INSERT\s+INTO|UPDATE|DELETE\s+FROM|DROP\s+TABLE|ALTER\s+TABLE)\s+schema_migrations\b/i;
const names = (await readdir(directory)).filter((name) => name.endsWith('.sql')).sort();
if (!names.length || names.some((name) => !/^[1-9]\d{9}_[a-z][a-z0-9_]*\.(up|down)\.sql$/.test(name))) {
  throw new Error('Migration filenames must use Unix seconds and up/down: 1234567890_description.up.sql');
}
const upNames = names.filter((name) => name.endsWith('.up.sql'));
if (names.length !== upNames.length * 2 || upNames.some((name) => !names.includes(name.replace('.up.sql', '.down.sql')))) {
  throw new Error('Each migration must have matching up/down files');
}
if (new Set(upNames.map((name) => name.slice(0, 10))).size !== upNames.length) throw new Error('Duplicate migration version');
const legacy = JSON.parse(await readFile(join(directory, 'legacy-manifest.json'), 'utf8'));
if (!Array.isArray(legacy?.migrations) || legacy.migrations.length > upNames.length) {
  throw new Error('Preserved legacy migration manifest differs');
}
const migrations = [];
const db = new DatabaseSync(':memory:');
const shapes = [];
const shape = () => db.prepare("SELECT type, name FROM sqlite_master WHERE name NOT LIKE 'sqlite_%' ORDER BY type, name").all()
  .map(({ type, name }) => ({ type, name, columns: type === 'table'
    ? db.prepare(`PRAGMA table_info("${name}")`).all().map(({ cid, ...column }) => column).sort((a, b) => a.name.localeCompare(b.name)) : [] }));
let targetSql;
try {
  db.exec('PRAGMA foreign_keys = ON');
  for (const [index, name] of upNames.entries()) {
    const files = [];
    for (const filename of [name, name.replace('.up.sql', '.down.sql')]) {
      const bytes = await readFile(join(directory, filename));
      if (!bytes.length || bytes[0] === 0xef || bytes.includes(13)) throw new Error(`Invalid migration encoding: ${filename}`);
      const sql = bytes.toString('utf8');
      if (unsafeSql.test(sql)) throw new Error(`Unsafe migration transaction or history control: ${filename}`);
      files.push({ name: filename, checksum: createHash('sha256').update(bytes).digest('hex'), sql });
    }
    const old = legacy.migrations[index];
    if (index < legacy.migrations.length && (!old || old.version !== Number(name.slice(0, 10)) || old.name !== name.replace('.up.sql', '.sql')
      || !/^[a-f0-9]{64}$/.test(old.checksum)
      || (index > 0 && old.checksum !== files[0].checksum))) throw new Error('Preserved legacy migration differs');
    shapes.push(shape());
    db.exec(files[0].sql);
    migrations.push({ version: Number(name.slice(0, 10)), name, checksum: files[0].checksum,
      down: { name: files[1].name, checksum: files[1].checksum }, downSql: files[1].sql });
  }
  const objects = db.prepare("SELECT sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'view' THEN 2 ELSE 3 END, name").all();
  targetSql = [
    '-- Generated by npm run migrations:manifest; do not edit directly.',
    `-- Target database version: ${migrations.at(-1).version}`,
    '-- Complete DDL for an empty database; use versioned migrations to upgrade existing data.',
    `PRAGMA application_id = ${db.prepare('PRAGMA application_id').get().application_id};`,
    'PRAGMA foreign_keys = ON;',
    '',
    objects.map(({ sql }) => `${sql};`).join('\n\n'),
    '',
  ].join('\n');
  for (let index = migrations.length - 1; index >= 0; index -= 1) {
    db.exec(migrations[index].downSql);
    const actual = index === 0 ? shape().filter(({ name }) => name !== 'schema_migrations') : shape();
    if (JSON.stringify(actual) !== JSON.stringify(shapes[index])) throw new Error(`Down migration does not restore the previous structure: ${migrations[index].down.name}`);
    if (db.prepare('PRAGMA foreign_key_check').all().length) throw new Error('Down migration violates foreign keys');
  }
} finally {
  db.close();
}
const text = `${JSON.stringify({ targetVersion: migrations.at(-1).version,
  migrations: migrations.map(({ downSql, ...entry }) => entry) }, null, 2)}\n`;
const file = join(directory, 'manifest.json');
const targetDirectory = resolve(directory, '../migration_target');
const targetFile = join(targetDirectory, 'schema.sql');
if (process.argv.includes('--check')) {
  if (await readFile(file, 'utf8') !== text) throw new Error('Migration manifest differs from SQL files');
  if (await readFile(targetFile, 'utf8') !== targetSql) throw new Error('Migration target differs from SQL files');
} else {
  await writeFile(file, text);
  await mkdir(targetDirectory, { recursive: true });
  await writeFile(targetFile, targetSql);
}
console.log(`${migrations.length} migration(s) verified`);
console.log('Complete migration target verified');
console.log('All down migrations restore previous object and column lists without FK violations');
